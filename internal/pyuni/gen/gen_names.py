#!/usr/bin/env python3
"""Write internal/pyuni/names.go: unicodedata.name / unicodedata.lookup data of CPython 3.12.

Names come from unicodedata.name() for every code point, except the algorithmic CJK UNIFIED
IDEOGRAPH-XXXX and HANGUL SYLLABLE names, which the Go side computes as CPython does. Aliases
(NameAliases.txt) cannot be enumerated through unicodedata, so the candidates in
alias_candidates.txt are kept when unicodedata.lookup() resolves them to a single code point.

The names are stored compressed: a word lexicon plus, per entry, the code point delta and the
word numbers as varints, base64-encoded.

Run from gold/internal/pyuni inside the pinned image:
    python3 gen/gen_names.py gen/alias_candidates.txt names.go testdata/names.sha256
"""
import base64
import hashlib
import sys
import unicodedata

MAX = 0x110000


def varint(n, out):
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return


def main():
    cand, outp, hashp = sys.argv[1:4]
    entries = []  # (cp, name, is_alias)
    cjk = []
    for c in range(MAX):
        n = unicodedata.name(chr(c), None)
        if n is None:
            continue
        if n.startswith("CJK UNIFIED IDEOGRAPH-"):
            cjk.append(c)
            continue
        if n.startswith("HANGUL SYLLABLE "):
            assert 0xAC00 <= c <= 0xD7A3
            continue
        entries.append((c, n, 0))
    aliases = 0
    for line in open(cand, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        cp, name = line.rstrip("\n").split("\t")
        c = int(cp, 16)
        try:
            got = unicodedata.lookup(name)
        except KeyError:
            continue
        if len(got) != 1 or ord(got) != c or unicodedata.name(got, None) == name:
            continue
        entries.append((c, name, 1))
        aliases += 1
    entries.sort()
    # CJK unified ideograph ranges
    ranges = []
    for c in cjk:
        if ranges and ranges[-1][1] == c - 1:
            ranges[-1][1] = c
        else:
            ranges.append([c, c])
    words = {}
    order = []
    for _, n, _ in entries:
        for w in n.split(" "):
            if w not in words:
                words[w] = len(order)
                order.append(w)
    data = bytearray()
    prev = 0
    for c, n, alias in entries:
        varint(c - prev, data)
        prev = c
        ws = n.split(" ")
        varint(len(ws) * 2 + alias, data)
        for w in ws:
            varint(words[w], data)
    b64 = base64.b64encode(bytes(data)).decode("ascii")
    lex = " ".join(order)
    assert "\\" not in lex and '"' not in lex
    lines = [
        "// Code generated by gen/gen_names.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). DO NOT EDIT.",
        "",
        "// Port of CPython 3.12's unicodedata / str character predicates (PSF License Version 2;",
        "// Copyright (c) 2001-2024 Python Software Foundation).",
        "",
        "package pyuni",
        "",
        f"// nameCount is the number of stored names and aliases ({aliases} aliases).",
        f"const nameCount = {len(entries)}",
        "",
        "// cjkRanges are the code point ranges named CJK UNIFIED IDEOGRAPH-XXXX.",
        "var cjkRanges = [][2]rune{",
    ]
    for a, b in ranges:
        lines.append(f"\t{{0x{a:x}, 0x{b:x}}},")
    lines.append("}")
    lines.append("")
    lines.append("// nameWords is the word lexicon of the names, space separated.")
    lines.append("const nameWords = \"\" +")
    chunk = 100
    parts = [lex[i:i + chunk] for i in range(0, len(lex), chunk)]
    for i, p in enumerate(parts):
        lines.append(f'\t"{p}"' + (" +" if i < len(parts) - 1 else ""))
    lines.append("")
    lines.append("// nameData is base64 of varints: code point delta, 2*words+alias, word numbers.")
    lines.append("const nameData = \"\" +")
    parts = [b64[i:i + chunk] for i in range(0, len(b64), chunk)]
    for i, p in enumerate(parts):
        lines.append(f'\t"{p}"' + (" +" if i < len(parts) - 1 else ""))
    with open(outp, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    # reference digest of name() for every code point (testdata)
    h = hashlib.sha256()
    for c in range(MAX):
        h.update(f"{c:x} {unicodedata.name(chr(c), '-')}\n".encode())
    with open(hashp, "w") as f:
        f.write(h.hexdigest() + "\n")
    print(f"{len(entries)} names ({aliases} aliases), {len(order)} words, {len(data)} bytes, {len(ranges)} CJK ranges")


if __name__ == "__main__":
    main()
