# Generates ../title_table.go: the code points whose str.title() differs from str.upper()
# in CPython 3.12 (Unicode 15.0.0). Run inside the pinned python:3.12-bookworm image:
#   python3 gen_title.py > ../title_table.go
import sys, unicodedata
assert sys.version_info[:2] == (3, 12), sys.version
rows = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    if c.title() != c.upper():
        rows.append((cp, c.title()))
def lit(s):
    return '"' + ''.join('\\U%08x' % ord(ch) for ch in s) + '"'
print("// Code generated by gen/gen_title.py from CPython %s (Unicode %s); DO NOT EDIT." % (sys.version.split()[0], unicodedata.unidata_version))
print()
print("// Port of CPython 3.12's _PyUnicode_ToTitleFull data (PSF License Version 2;")
print("// Copyright (c) 2001-2024 Python Software Foundation).")
print()
print("package pyval")
print()
print("// titleSpecial maps each code point whose full titlecase mapping differs from its full")
print("// uppercase mapping to the titlecase mapping.")
print("var titleSpecial = map[rune]string{")
for cp, t in rows:
    print("\t0x%04x: %s," % (cp, lit(t)))
print("}")
